#!/usr/bin/env python3
"""Generate a C header that carries the FusedLocation APK inside init.

Why not the ramfs: boot 1967557b showed

    gfx: overlay /system/priv-app rc=0 errno=0 (ok)
    gfx: system-overlay/priv-app/FusedLocation/FusedLocation.apk is not on the ramdisk: 2

while all nine vendor-overlay files copied fine from the same initrd and the same
dirfd. The archive itself is provably correct (gzip -dc + cpio extracts the APK
with sha256 c9e2ee86…), and vendor-overlay also exists in the *kernel's built-in*
initramfs, so the one thing that differs is that system-overlay is a name that only
the external initrd carries -- and it never showed up in the old root the first
stage reads from.

Rather than keep guessing, embed the APK in the init binary: a hex string decodes
back to the exact bytes, so nothing depends on how the ramdisk is unpacked.

Run tools/build-fused-location.sh, which calls this after building the APK.
"""

import hashlib
import os
import sys

APK = "/root/android/lineage/out/target/product/rg34xxsp/system/priv-app/FusedLocation/FusedLocation.apk"
OUT = "/root/android/lineage/system/core/init/dsh-fused-location-apk.h"

CHUNK = 96  # characters per source line


def main():
    if not os.path.isfile(APK):
        sys.exit("missing APK: %s" % APK)
    blob = open(APK, "rb").read()
    digest = hashlib.sha256(blob).hexdigest()
    hexstr = blob.hex()

    lines = []
    for i in range(0, len(hexstr), CHUNK):
        lines.append('    "%s"' % hexstr[i:i + CHUNK])

    body = "\n".join(lines)
    text = f"""// GENERATED by tools/embed-fused-location-apk.py -- do not edit.
//
// {os.path.basename(APK)} ({len(blob)} bytes)
// sha256 {digest}
//
// The APK is hex-encoded here and decoded at first-stage time straight into
// /system/priv-app/FusedLocation/FusedLocation.apk, because reading it back out of
// the unpacked initramfs turned out not to work (see doubt in the generator's
// docstring and patches/patch-fused-location-embed.py).
#pragma once

static const char kFusedLocationApkHex[] =
{body}
;
static const unsigned kFusedLocationApkLen = {len(blob)};
static const char kFusedLocationApkSha256[] = "{digest}";
"""
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d bytes, apk %d bytes, sha %s)" % (OUT, len(text), len(blob), digest))


main()